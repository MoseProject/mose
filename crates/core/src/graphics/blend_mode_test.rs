#[test]
fn matches_ffmpeg_blend_filter_output_for_every_non_normal_mode() {
    for &(mode, top, bottom, expected) in VECTORS {
        let actual = blend_channel(mode, top, bottom);
        assert_eq!(
            actual, expected,
            "{mode:?}: blend_channel({top}, {bottom}) = {actual}, expected {expected}"
        );
    }
}

#[test]
fn interpolate_matches_ffmpeg_within_rounding_tolerance() {
    let cases: &[(u8, u8, u8)] = &[
        (0, 0, 0),
        (255, 255, 255),
        (0, 255, 128),
        (255, 0, 128),
        (128, 64, 83),
        (64, 200, 132),
        (200, 50, 125),
        (1, 254, 128),
    ];
    for &(top, bottom, expected) in cases {
        let actual = blend_channel(BlendMode::Interpolate, top, bottom);
        let diff = (actual as i32 - expected as i32).abs();
        assert!(
            diff <= 1,
            "Interpolate({top}, {bottom}) = {actual}, expected {expected} (+/-1)"
        );
    }
}

#[test]
fn normal_mode_returns_top_unchanged() {
    for top in [0u8, 1, 128, 254, 255] {
        for bottom in [0u8, 64, 255] {
            assert_eq!(blend_channel(BlendMode::Normal, top, bottom), top);
        }
    }
}
